  ADD COLUMN IF NOT EXISTS allowed_actions JSONB NOT NULL DEFAULT '{}'::jsonb;

CREATE TABLE IF NOT EXISTS public.creator_module_settings (
  module_key TEXT PRIMARY KEY,
  status TEXT NOT NULL DEFAULT 'under_review'
    CHECK (status IN ('active', 'maintenance', 'disabled', 'under_review', 'not_configured')),
  message TEXT,
  updated_by BIGINT,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.creator_admin_audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_user_id BIGINT,
  actor_role TEXT NOT NULL,
  actor_name TEXT,
  module_key TEXT NOT NULL,
  action_key TEXT NOT NULL,
  target_type TEXT,
  target_id TEXT,
  outcome TEXT NOT NULL DEFAULT 'success'
    CHECK (outcome IN ('success', 'denied', 'failed')),
  safe_metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_creator_admin_audit_created
  ON public.creator_admin_audit_logs (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_creator_admin_audit_actor
  ON public.creator_admin_audit_logs (actor_user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_creator_admin_audit_module
  ON public.creator_admin_audit_logs (module_key, created_at DESC);

ALTER TABLE public.creator_module_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.creator_admin_audit_logs ENABLE ROW LEVEL SECURITY;

