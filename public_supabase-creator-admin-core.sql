CREATE OR REPLACE FUNCTION public.creator_admin_dashboard_summary()
RETURNS JSONB
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, extensions
AS $$
DECLARE
  v_table TEXT;
  v_count BIGINT;
  v_counts JSONB := '{}'::jsonb;
  v_tables TEXT[] := ARRAY[
    'users', 'exchanges', 'customers', 'documents',
    'transfers', 'ledger_entries', 'audit_logs'
  ];
BEGIN
  PERFORM public.creator_admin_require('system', 'view');

  FOREACH v_table IN ARRAY v_tables LOOP
    IF to_regclass('public.' || v_table) IS NULL THEN
      v_counts := v_counts || jsonb_build_object(v_table, NULL);
    ELSE
      EXECUTE format('SELECT COUNT(*) FROM public.%I', v_table) INTO v_count;
      v_counts := v_counts || jsonb_build_object(v_table, v_count);
    END IF;
  END LOOP;

  RETURN jsonb_build_object(
    'generated_at', now(),
    'database_size_bytes', pg_database_size(current_database()),
    'table_counts', v_counts
  );
END;
$$;

