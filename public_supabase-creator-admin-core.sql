CREATE OR REPLACE FUNCTION public.creator_admin_context()
RETURNS JSONB
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, extensions
AS $$
DECLARE
  v_claims JSONB;
  v_uid BIGINT;
  v_user RECORD;
  v_access RECORD;
BEGIN
  v_claims := public.app_claims();
  IF v_claims IS NULL THEN
    RETURN jsonb_build_object('authenticated', false, 'authorized', false, 'role', 'guest', 'allowed_tabs', '[]'::jsonb);
  END IF;

  BEGIN
    v_uid := NULLIF(v_claims ->> 'uid', '')::BIGINT;
  EXCEPTION WHEN OTHERS THEN
    RETURN jsonb_build_object('authenticated', false, 'authorized', false, 'role', 'guest', 'allowed_tabs', '[]'::jsonb);
  END;

  SELECT id, full_name, email, mobile, role, status
    INTO v_user
  FROM public.users
  WHERE id = v_uid;

  IF NOT FOUND OR COALESCE(v_user.status, 'active') <> 'active' THEN
    RETURN jsonb_build_object('authenticated', false, 'authorized', false, 'role', 'inactive', 'allowed_tabs', '[]'::jsonb);
  END IF;

  -- Only the database's current creator role grants primary access.
  -- A stale role claim in an old HMAC token cannot promote a different DB role.
  IF v_user.role = 'creator' THEN
    RETURN jsonb_build_object(
      'authenticated', true,
      'authorized', true,
      'role', 'creator',
      'user_id', v_user.id::TEXT,
      'name', COALESCE(v_user.full_name, 'سازنده اصلی'),
      'allowed_tabs', '"all"'::jsonb,
      'allowed_actions', '"all"'::jsonb
    );
  END IF;

  -- Existing helper records are matched against the verified server-side user identity.
  SELECT ba.id, ba.name, ba.allowed_tabs, ba.allowed_actions, ba.status
    INTO v_access
  FROM public.builder_access ba
  WHERE COALESCE(ba.status, 'active') = 'active'
    AND (
      (COALESCE(v_user.email, '') <> ''
        AND LOWER(BTRIM(COALESCE(ba.email, ''))) = LOWER(BTRIM(v_user.email)))
      OR
      (REGEXP_REPLACE(COALESCE(v_user.mobile, ''), '[^0-9]', '', 'g') <> ''
        AND REGEXP_REPLACE(COALESCE(ba.phone, ''), '[^0-9]', '', 'g')
          = REGEXP_REPLACE(COALESCE(v_user.mobile, ''), '[^0-9]', '', 'g'))
    )
  ORDER BY ba.id DESC
  LIMIT 1;

  IF FOUND THEN
    RETURN jsonb_build_object(
      'authenticated', true,
      'authorized', true,
      'role', 'co_creator',
      'user_id', v_user.id::TEXT,
      'access_id', v_access.id::TEXT,
      'name', COALESCE(v_access.name, v_user.full_name, 'کمک‌سازنده'),
      'allowed_tabs', COALESCE(v_access.allowed_tabs, '[]'::jsonb),
      'allowed_actions', COALESCE(v_access.allowed_actions, '{}'::jsonb)
    );
  END IF;

  RETURN jsonb_build_object(
    'authenticated', true,
    'authorized', false,
    'role', COALESCE(v_user.role, 'user'),
    'user_id', v_user.id::TEXT,
    'allowed_tabs', '[]'::jsonb,
    'allowed_actions', '{}'::jsonb
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.creator_admin_require(
  p_module_key TEXT,
  p_action_key TEXT DEFAULT 'view'
)
RETURNS JSONB
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, extensions
AS $$
DECLARE
  v_actor JSONB;
  v_tabs JSONB;
  v_actions JSONB;
BEGIN
  v_actor := public.creator_admin_context();
  IF COALESCE((v_actor ->> 'authorized')::BOOLEAN, false) IS NOT TRUE THEN
    RAISE EXCEPTION 'creator_access_denied' USING ERRCODE = '42501';
  END IF;

  IF v_actor ->> 'role' = 'creator' THEN
    RETURN v_actor;
  END IF;

  IF p_module_key = 'co_creators' THEN
    RAISE EXCEPTION 'creator_only_module' USING ERRCODE = '42501';
  END IF;

  v_tabs := COALESCE(v_actor -> 'allowed_tabs', '[]'::jsonb);
  IF jsonb_typeof(v_tabs) <> 'array' OR NOT (v_tabs ? p_module_key) THEN
    RAISE EXCEPTION 'module_access_denied' USING ERRCODE = '42501';
  END IF;

  -- A tab grant grants view only. Mutations need an explicit per-module action.
  IF p_action_key <> 'view' THEN
    v_actions := COALESCE(v_actor -> 'allowed_actions' -> p_module_key, '[]'::jsonb);
    IF jsonb_typeof(v_actions) <> 'array' OR NOT (v_actions ? p_action_key) THEN
      RAISE EXCEPTION 'module_action_denied' USING ERRCODE = '42501';
    END IF;
  END IF;

  RETURN v_actor;
END;
$$;

