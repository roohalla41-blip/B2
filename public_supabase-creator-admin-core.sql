CREATE OR REPLACE FUNCTION public.creator_admin_set_module_status(
  p_module_key TEXT,
  p_status TEXT,
  p_message TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions
AS $$
DECLARE
  v_actor JSONB;
  v_row public.creator_module_settings;
  v_allowed TEXT[] := ARRAY[
    'system', 'features', 'users', 'perms', 'plans', 'pricing',
    'notif', 'chat', 'payments', 'withdrawals', 'version',
    'backup', 'backup_v2', 'triple_backup', 'co_creators',
    'email_verify', 'trial', 'layout_preview', 'masnavi_ai',
    'uc_manager', 'recharge', 'afghan5', 'sellers', 'sandbox',
    'supabase_audit', 'db_explorer'
  ];
BEGIN
  v_actor := public.creator_admin_require('features', 'manage');
  IF NOT (p_module_key = ANY(v_allowed)) THEN
    RAISE EXCEPTION 'unknown_creator_module' USING ERRCODE = '22023';
  END IF;
  IF p_status NOT IN ('active', 'maintenance', 'disabled', 'under_review', 'not_configured') THEN
    RAISE EXCEPTION 'invalid_module_status' USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.creator_module_settings (module_key, status, message, updated_by, updated_at)
  VALUES (p_module_key, p_status, NULLIF(BTRIM(p_message), ''), (v_actor ->> 'user_id')::BIGINT, now())
  ON CONFLICT (module_key) DO UPDATE
    SET status = EXCLUDED.status,
        message = EXCLUDED.message,
        updated_by = EXCLUDED.updated_by,
        updated_at = now()
  RETURNING * INTO v_row;

  INSERT INTO public.creator_admin_audit_logs
    (actor_user_id, actor_role, actor_name, module_key, action_key, target_type, target_id, outcome)
  VALUES
    ((v_actor ->> 'user_id')::BIGINT, v_actor ->> 'role', v_actor ->> 'name',
     'features', 'module_status_update', 'creator_module_settings', p_module_key, 'success');

  RETURN to_jsonb(v_row);
END;
$$;

CREATE OR REPLACE FUNCTION public.creator_admin_list_users(
  p_search TEXT DEFAULT NULL,
  p_role TEXT DEFAULT NULL,
  p_limit INTEGER DEFAULT 50,
  p_offset INTEGER DEFAULT 0
)
RETURNS JSONB
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, extensions
AS $$
DECLARE
  v_items JSONB;
  v_actor JSONB;
BEGIN
  v_actor := public.creator_admin_require('users', 'view');
  SELECT COALESCE(jsonb_agg(to_jsonb(q)), '[]'::jsonb)
    INTO v_items
  FROM (
    SELECT
      u.id::TEXT AS id,
      u.full_name,
      u.username,
      u.email,
      u.mobile,
      u.role,
      u.status,
      u.created_at,
      u.last_login
    FROM public.users u
    WHERE
      (NULLIF(BTRIM(p_role), '') IS NULL OR u.role = p_role)
      AND (
        NULLIF(BTRIM(p_search), '') IS NULL
        OR u.full_name ILIKE '%' || BTRIM(p_search) || '%'
        OR u.username ILIKE '%' || BTRIM(p_search) || '%'
        OR u.email ILIKE '%' || BTRIM(p_search) || '%'
        OR u.mobile ILIKE '%' || BTRIM(p_search) || '%'
      )
    ORDER BY u.created_at DESC NULLS LAST, u.id DESC
    LIMIT LEAST(GREATEST(COALESCE(p_limit, 50), 1), 100)
    OFFSET GREATEST(COALESCE(p_offset, 0), 0)
  ) q;

  RETURN jsonb_build_object('items', v_items, 'requested_by', v_actor ->> 'user_id');
END;
$$;

