CREATE OR REPLACE FUNCTION public.creator_admin_save_co_creator(
  p_id BIGINT DEFAULT NULL,
  p_name TEXT DEFAULT NULL,
  p_email TEXT DEFAULT NULL,
  p_phone TEXT DEFAULT NULL,
  p_allowed_tabs JSONB DEFAULT '[]'::jsonb,
  p_allowed_actions JSONB DEFAULT '{}'::jsonb,
  p_notes TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions
AS $$
DECLARE
  v_actor JSONB;
  v_row public.builder_access;
  v_tab TEXT;
  v_valid_tabs TEXT[] := ARRAY[
    'system', 'features', 'users', 'perms', 'plans', 'pricing',
    'notif', 'chat', 'payments', 'withdrawals', 'version',
    'backup', 'backup_v2', 'triple_backup', 'email_verify',
    'trial', 'layout_preview', 'masnavi_ai', 'uc_manager',
    'recharge', 'afghan5', 'sellers', 'sandbox', 'supabase_audit', 'db_explorer'
  ];
BEGIN
  v_actor := public.creator_admin_require('co_creators', 'manage');

  IF NULLIF(BTRIM(p_name), '') IS NULL
     OR (NULLIF(BTRIM(p_email), '') IS NULL AND NULLIF(BTRIM(p_phone), '') IS NULL) THEN
    RAISE EXCEPTION 'co_creator_name_and_identifier_required' USING ERRCODE = '22023';
  END IF;
  IF jsonb_typeof(COALESCE(p_allowed_tabs, '[]'::jsonb)) <> 'array' THEN
    RAISE EXCEPTION 'allowed_tabs_must_be_array' USING ERRCODE = '22023';
  END IF;

  FOR v_tab IN SELECT jsonb_array_elements_text(COALESCE(p_allowed_tabs, '[]'::jsonb)) LOOP
    IF NOT (v_tab = ANY(v_valid_tabs)) OR v_tab = 'co_creators' THEN
      RAISE EXCEPTION 'invalid_or_forbidden_tab' USING ERRCODE = '22023';
    END IF;
  END LOOP;

  IF p_id IS NULL THEN
    INSERT INTO public.builder_access
      (name, email, phone, allowed_tabs, allowed_actions, status, notes)
    VALUES
      (BTRIM(p_name), LOWER(NULLIF(BTRIM(p_email), '')), NULLIF(BTRIM(p_phone), ''),
       COALESCE(p_allowed_tabs, '[]'::jsonb), COALESCE(p_allowed_actions, '{}'::jsonb),
       'active', NULLIF(BTRIM(p_notes), ''))
    RETURNING * INTO v_row;
  ELSE
    UPDATE public.builder_access
    SET name = BTRIM(p_name),
        email = LOWER(NULLIF(BTRIM(p_email), '')),
        phone = NULLIF(BTRIM(p_phone), ''),
        allowed_tabs = COALESCE(p_allowed_tabs, '[]'::jsonb),
        allowed_actions = COALESCE(p_allowed_actions, '{}'::jsonb),
        notes = NULLIF(BTRIM(p_notes), ''),
        updated_at = now()
    WHERE id = p_id
    RETURNING * INTO v_row;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'co_creator_not_found' USING ERRCODE = 'P0002';
    END IF;
  END IF;

  INSERT INTO public.creator_admin_audit_logs
    (actor_user_id, actor_role, actor_name, module_key, action_key, target_type, target_id, outcome)
  VALUES
    ((v_actor ->> 'user_id')::BIGINT, v_actor ->> 'role', v_actor ->> 'name',
     'co_creators', CASE WHEN p_id IS NULL THEN 'create' ELSE 'update' END,
     'builder_access', v_row.id::TEXT, 'success');

  RETURN jsonb_build_object(
    'id', v_row.id::TEXT,
    'name', v_row.name,
    'email', v_row.email,
    'phone', v_row.phone,
    'allowed_tabs', v_row.allowed_tabs,
    'allowed_actions', v_row.allowed_actions,
    'status', v_row.status,
    'notes', v_row.notes,
    'created_at', v_row.created_at,
    'updated_at', v_row.updated_at
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.creator_admin_set_co_creator_status(
  p_id BIGINT,
  p_status TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, extensions
AS $$
DECLARE
  v_actor JSONB;
  v_row public.builder_access;
BEGIN
  v_actor := public.creator_admin_require('co_creators', 'manage');
  IF p_status NOT IN ('active', 'suspended') THEN
    RAISE EXCEPTION 'invalid_co_creator_status' USING ERRCODE = '22023';
  END IF;

  UPDATE public.builder_access
  SET status = p_status, updated_at = now()
  WHERE id = p_id
  RETURNING * INTO v_row;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'co_creator_not_found' USING ERRCODE = 'P0002';
  END IF;

  INSERT INTO public.creator_admin_audit_logs
    (actor_user_id, actor_role, actor_name, module_key, action_key, target_type, target_id, outcome)
  VALUES
    ((v_actor ->> 'user_id')::BIGINT, v_actor ->> 'role', v_actor ->> 'name',
     'co_creators', 'status_change', 'builder_access', v_row.id::TEXT, 'success');

  RETURN jsonb_build_object('id', v_row.id::TEXT, 'status', v_row.status, 'updated_at', v_row.updated_at);
END;
$$;

CREATE OR REPLACE FUNCTION public.creator_admin_list_audit(
  p_limit INTEGER DEFAULT 100
)
RETURNS JSONB
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, extensions
AS $$
BEGIN
  PERFORM public.creator_admin_require('system', 'view');
  RETURN COALESCE(
    (
      SELECT jsonb_agg(to_jsonb(a) ORDER BY a.created_at DESC, a.id DESC)
      FROM (
        SELECT id, actor_user_id::TEXT, actor_role, actor_name, module_key,
               action_key, target_type, target_id, outcome, safe_metadata, created_at
        FROM public.creator_admin_audit_logs
        ORDER BY created_at DESC, id DESC
        LIMIT LEAST(GREATEST(COALESCE(p_limit, 100), 1), 200)
      ) a
    ),
    '[]'::jsonb
  );
END;
$$;

